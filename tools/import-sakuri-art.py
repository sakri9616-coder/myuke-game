# ---------------------------------------------------------------- palette ---
def load_palette(sprites_js_text):
    """sprites.js の palette ブロックから {char: '#RRGGBB'} を読む"""
    m = re.search(r"palette:\s*\{(.*?)\n\s*\},", sprites_js_text, re.S)
    if not m:
        raise ValueError("palette block not found in sprites.js")
    pal = {}
    for ch, hexv in re.findall(r'"(.?)":\s*"(#[0-9A-Fa-f]{6})"', m.group(1)):
        pal[ch] = hexv.upper()
    return pal


def frames_to_rows(frames, palette, hex_to_char):
    """RGBA フレーム群 (PIL Image のリスト) → {行文字列リスト} と監査情報。
    palette / hex_to_char は必要に応じて拡張され、追加した {char: hex} を返す。"""
    added = {}
    used_hex = set()
    all_rows = []
    semi = []
    for fi, img in enumerate(frames):
        px = img.load()
        w, h = img.size
        rows = []
        for y in range(h):
            chars = []
            for x in range(w):
                r, g, b, a = px[x, y]
                if a == 0:
                    chars.append(".")
                    continue
                if a != 255:
                    semi.append((fi, x, y, a))
                hexv = "#%02X%02X%02X" % (r, g, b)
                used_hex.add(hexv)
                ch = hex_to_char.get(hexv)
                if ch is None:
                    for cand in CHAR_POOL:
                        if cand not in palette:
                            ch = cand
                            break
                    if ch is None:
                        raise ValueError("palette char pool exhausted")
                    palette[ch] = hexv
                    hex_to_char[hexv] = ch
                    added[ch] = hexv
                chars.append(ch)
            rows.append("".join(chars))
        all_rows.append(rows)
    return all_rows, {"used_hex": sorted(used_hex), "added": added, "semi_alpha": semi}


# ------------------------------------------------------------- PNG sheet ---
def read_sheet(path, cell_w, cell_h):
    img = Image.open(path).convert("RGBA")
    W, H = img.size
    if H != cell_h or W % cell_w != 0:
        raise ValueError(
            "sheet size %dx%d is not a horizontal strip of %dx%d cells" % (W, H, cell_w, cell_h))
    frames = []
    for i in range(W // cell_w):
        frames.append(img.crop((i * cell_w, 0, (i + 1) * cell_w, cell_h)))
    return frames


# -------------------------------------------------------------- aseprite ---
def _u16(d, p):
    return struct.unpack_from("<H", d, p)[0]


def _i16(d, p):
    return struct.unpack_from("<h", d, p)[0]


def _u32(d, p):
    return struct.unpack_from("<I", d, p)[0]


def parse_tags_chunk(body):
    """タグ chunk (0x2022) をパースする。
    形式: WORD 個数, BYTE[8] 予約, タグごとに
      WORD from, WORD to, BYTE 向き, WORD repeat, BYTE[6] 予約,
      BYTE[4] 色, BYTE 予備, STRING 名前 (WORD 長 + UTF-8)。
    repeat は「区間を何周するか」。0 は未指定（無限として扱う）。"""
    tags = []
    if len(body) < 10:
        return tags
    n = _u16(body, 0)
    p = 10
    for _ in range(n):
        if p + 18 > len(body):
            break
        frm, to = _u16(body, p), _u16(body, p + 2)
        direction = body[p + 4]
        repeat = _u16(body, p + 5)
        nlen = _u16(body, p + 17)
        name = body[p + 19: p + 19 + nlen].decode("utf-8", "replace")
        tags.append({"name": name, "from": frm, "to": to,
                     "direction": direction, "repeat": repeat})
        p += 19 + nlen
    return tags


def parse_palette_chunk(body):
    """パレット chunk (0x2019) をパースする。
    形式: DWORD 総数, DWORD 開始index, DWORD 終了index, BYTE[8] 予約,
    エントリごとに WORD flags, BYTE R,G,B,A (+ flags&1 のとき STRING 名前)。"""
    if len(body) < 20:
        return []
    size = _u32(body, 0)
    first, last = _u32(body, 4), _u32(body, 8)
    entries = [(0, 0, 0, 0)] * size
    p = 20
    for idx in range(first, last + 1):
        if p + 6 > len(body) or idx >= size:
            break
        flags = _u16(body, p)
        r, g, b, a = body[p + 2], body[p + 3], body[p + 4], body[p + 5]
        p += 6
        if flags & 1:
            nlen = _u16(body, p)
            p += 2 + nlen
        entries[idx] = (r, g, b, a)
    return entries


def parse_aseprite(path):
    """Aseprite バイナリをパースし、合成済み RGBA フレーム (PIL Image) のリスト、
    フレーム継続時間 (ms) のリスト、タグのリストを返す。
    32bpp RGBA と 8bpp インデックスカラー（パレット chunk 0x2019）に対応する。"""
    data = open(path, "rb").read()
    if len(data) < 128 or _u16(data, 4) != 0xA5E0:
        raise ValueError("not an aseprite file (bad magic)")
    nframes = _u16(data, 6)
    W, H = _u16(data, 8), _u16(data, 10)
    depth = _u16(data, 12)
    if depth not in (32, 8):
        raise ValueError("only 32bpp RGBA / 8bpp indexed aseprite files are supported (got %d)" % depth)
    bpp = 4 if depth == 32 else 1
    transparent_idx = data[28]   # ヘッダの透過色 index（8bpp 用）

    layers = []          # index 順 = 下から上
    raw_frames = []      # frame -> { layer_index: cel dict }
    durations = []
    tags = []
    palette_entries = []  # 8bpp 用。パレット chunk は大抵フレーム0にある
    pos = 128
    for fi in range(nframes):
        fsize = _u32(data, pos)
        if _u16(data, pos + 4) != 0xF1FA:
            raise ValueError("bad frame magic at frame %d" % fi)
        old_count = _u16(data, pos + 6)
        durations.append(_u16(data, pos + 8))
        new_count = _u32(data, pos + 12)
        nchunks = new_count if old_count == 0xFFFF else old_count
        cpos = pos + 16
        cels = {}
        for _ in range(nchunks):
            csize = _u32(data, cpos)
            ctype = _u16(data, cpos + 4)
            cd = cpos + 6
            if ctype == 0x2004:  # ---- layer chunk
                flags, ltype = _u16(data, cd), _u16(data, cd + 2)
                blend = _u16(data, cd + 10)
                opacity = data[cd + 12]
                nlen = _u16(data, cd + 16)
                name = data[cd + 18: cd + 18 + nlen].decode("utf-8", "replace")
                layers.append({"flags": flags, "type": ltype, "blend": blend,
                               "opacity": opacity, "name": name})
            elif ctype == 0x2005:  # ---- cel chunk
                li = _u16(data, cd)
                x, y = _i16(data, cd + 2), _i16(data, cd + 4)
                opacity = data[cd + 6]
                celtype = _u16(data, cd + 7)
                if celtype == 1:  # linked cel
                    link = _u16(data, cd + 16)
                    cels[li] = {"link": link, "x": x, "y": y, "opacity": opacity}
                elif celtype in (0, 2):  # raw / zlib-compressed image
                    w, h = _u16(data, cd + 16), _u16(data, cd + 18)
                    raw = data[cd + 20: cpos + csize]
                    if celtype == 2:
                        raw = zlib.decompress(raw)
                    if len(raw) < w * h * bpp:
                        raise ValueError("cel pixel data too short (frame %d layer %d)" % (fi, li))
                    # ピクセル→画像の変換は遅延する（8bpp のパレット chunk が
                    # 後続フレームにある場合でも解決できるように）
                    cels[li] = {"rawpx": raw[: w * h * bpp], "w": w, "h": h,
                                "x": x, "y": y, "opacity": opacity}
                else:
                    raise ValueError("unsupported cel type %d (tilemap?)" % celtype)
            elif ctype == 0x2019:  # ---- palette chunk (8bpp 用)
                palette_entries = parse_palette_chunk(data[cd: cpos + csize])
            elif ctype in (0x2018, 0x2022):  # ---- tags chunk (0x2018 = 標準 / 0x2022 = 新版)
                # 2026-10-25 修正: sakuri の .aseprite は 0x2018 でタグを保存しており、
                # 0x2022 しか見ていなかったため全スタッフのタグ (walk_loop 等) を
                # 取りこぼしていた (walk に BacktoIdle フレームが混入するバグの根因)
                tags.extend(parse_tags_chunk(data[cd: cpos + csize]))
            cpos += csize
        raw_frames.append(cels)
        pos += fsize

    def cel_pixels_to_image(raw, w, h):
        if depth == 32:
            return Image.frombytes("RGBA", (w, h), raw)
        # 8bpp: パレット index → RGBA。ヘッダの透過 index は alpha 0 にする
        if not palette_entries:
            raise ValueError("8bpp file without a palette chunk (0x2019)")
        img = Image.new("RGBA", (w, h))
        px = img.load()
        for i in range(w * h):
            idx = raw[i]
            if idx == transparent_idx or idx >= len(palette_entries):
                px[i % w, i // w] = (0, 0, 0, 0)
            else:
                px[i % w, i // w] = palette_entries[idx]
        return img

    def resolve_cel(fi, li, depth_guard=0):
        if depth_guard > nframes + 2:
            raise ValueError("linked cel cycle detected")
        cel = raw_frames[fi].get(li)
        if cel is None:
            return None
        if "link" in cel:
            target = resolve_cel(cel["link"], li, depth_guard + 1)
            if target is None:
                return None
            merged = dict(target)
            merged["x"], merged["y"] = cel["x"], cel["y"]
            merged["opacity"] = cel["opacity"]
            return merged
        if "img" not in cel and "rawpx" in cel:
            cel = dict(cel)
            cel["img"] = cel_pixels_to_image(cel["rawpx"], cel["w"], cel["h"])
        return cel

    frames = []
    for fi in range(nframes):
        canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        for li, layer in enumerate(layers):
            if layer["type"] != 0:
                continue  # グループ層などは描画しない
            if not (layer["flags"] & 1):
                continue  # 非表示レイヤー
            cel = resolve_cel(fi, li)
            if cel is None or "img" not in cel:
                continue
            eff_opacity = layer["opacity"] * cel["opacity"]  # 0..65025
            layer_img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            layer_img.paste(cel["img"], (cel["x"], cel["y"]))
            if eff_opacity < 65025:
                alpha = layer_img.getchannel("A")
                alpha = alpha.point(lambda a: a * eff_opacity // 65025)
                layer_img.putalpha(alpha)
            canvas = Image.alpha_composite(canvas, layer_img)
        frames.append(canvas)
    return frames, durations, tags


# ------------------------------------------------------------ loop 解決 ---
def parse_loop_arg(text):
    """"3:14x3" / "3:14" / "1:6xinf" → (from0, to0, count)。番号は 1 始まり。"""
    m = re.fullmatch(r"(\d+):(\d+)(?:x(\d+|inf))?", text.strip(), re.I)
    if not m:
        raise ValueError("--loop は FROM:TO[xN|xinf] 形式 (例: 3:14x3)")
    frm, to = int(m.group(1)) - 1, int(m.group(2)) - 1
    cnt = m.group(3)
    count = float("inf") if (cnt is None or cnt.lower() == "inf") else int(cnt)
    return frm, to, count


DIRECTION_NAMES = {0: "forward", 1: "reverse", 2: "pingpong", 3: "pingpong_reverse"}


def resolve_loop(nframes, tags, loop_arg):
    """(loopFrom, loopTo, loopCount, 出所, direction) を決める。0 始まり・両端含む。
    direction は Aseprite タグの向き（0=forward 1=reverse 2=pingpong
    3=pingpong_reverse）。タグが無い指定方法では forward 固定。"""
    for t in tags:
        if "loop" in t["name"].lower():
            cnt = t["repeat"] if t["repeat"] and t["repeat"] > 0 else float("inf")
            return (t["from"], t["to"], cnt, "aseprite tag '%s'" % t["name"],
                    DIRECTION_NAMES.get(t["direction"], "forward"))
    if loop_arg:
        frm, to, cnt = parse_loop_arg(loop_arg)
        return frm, to, cnt, "--loop", "forward"
    return 0, nframes - 1, float("inf"), "default (whole range)", "forward"


# ------------------------------------------------------- sprites.js 更新 ---
def entry_text(name, rows):
    lines = ["    %s: [" % name]
    for row in rows:
        lines.append('      "%s",' % row)
    lines.append("    ],")
    return "\n".join(lines) + "\n"


def update_sprites_js(text, base_name, all_rows, palette, orig_palette_size, static=False):
    """base_name_N エントリを base_name の直後へ挿入（既存の同名連番は置き換え）。
    static=True のときは連番にせず base_name 自体を 1 枚で置き換える。
    パレットに色が増えていたら palette ブロックへも行を追加する。"""
    # --- パレット拡張
    if len(palette) > orig_palette_size:
        existing = load_palette(text)
        new_lines = []
        for ch, hexv in palette.items():
            if ch not in existing:
                new_lines.append('    "%s": "%s",\n' % (ch, hexv))
        m = re.search(r"(palette:\s*\{.*?)(\n\s*\},)", text, re.S)
        text = (text[: m.end(1)] + "\n" + "".join(new_lines).rstrip("\n")
                + text[m.start(2):])
    if static:
        pat = re.compile(r"    %s: \[\n(?:.*\n)*?    \],\n" % re.escape(base_name))
        text = pat.sub("", text)
        block = entry_text(base_name, all_rows[0])
        tail = re.search(r"(\n\s*\}\n\};)", text)
        return text[: tail.start(1)] + "\n" + block + text[tail.start(1):]
    # --- 既存の連番エントリを除去（再実行時の冪等性）
    pat = re.compile(r"    %s_\d+: \[\n(?:.*\n)*?    \],\n" % re.escape(base_name))
    text = pat.sub("", text)
    # --- 生成
    block = "".join(entry_text("%s_%d" % (base_name, i), rows)
                    for i, rows in enumerate(all_rows))
    # --- 挿入位置: base_name エントリの直後。無ければ sprites 末尾
    anchor = re.compile(r"(    %s: \[\n(?:.*\n)*?    \],\n)" % re.escape(base_name))
    m = anchor.search(text)
    if m:
        text = text[: m.end(1)] + block + text[m.end(1):]
    else:
        tail = re.search(r"(\n\s*\}\n\};)", text)
        text = text[: tail.start(1)] + "\n" + block + text[tail.start(1):]
    return text


# ------------------------------------------------------------- ANIMS 生成 ---
def load_existing_anims(text):
    """生成ブロック内の既存エントリを {base: dict} で読む（他アセットの分を保持する）。"""
    anims = {}
    m = re.search(re.escape(ANIMS_BEGIN) + r"(.*?)" + re.escape(ANIMS_END), text, re.S)
    if not m:
        return anims
    for em in re.finditer(r"(\w+):\s*\{\s*frames:\s*\[(.*?)\],\s*durations:\s*\[(.*?)\],"
                          r"\s*loopFrom:\s*(\d+),\s*loopTo:\s*(\d+),\s*loopCount:\s*(Infinity|\d+)"
                          r"(?:\s*,\s*direction:\s*\"(\w+)\")?\s*\}",
                          m.group(1), re.S):
        anims[em.group(1)] = {
            "frames": re.findall(r'"([^"]+)"', em.group(2)),
            "durations": [int(v) for v in re.findall(r"\d+", em.group(3))],
            "loopFrom": int(em.group(4)), "loopTo": int(em.group(5)),
            "loopCount": float("inf") if em.group(6) == "Infinity" else int(em.group(6)),
            "direction": em.group(7) or "forward",
        }
    return anims


def anims_block_text(anims):
    lines = [ANIMS_BEGIN, "window.MIYUKE_ANIMS = {"]
    for base in sorted(anims):
        a = anims[base]
        cnt = "Infinity" if a["loopCount"] == float("inf") else str(int(a["loopCount"]))
        lines.append("  %s: {" % base)
        lines.append("    frames: %s," % json.dumps(a["frames"]))
        lines.append("    durations: %s," % json.dumps(a["durations"]))
        lines.append("    loopFrom: %d, loopTo: %d, loopCount: %s, direction: \"%s\""
                     % (a["loopFrom"], a["loopTo"], cnt, a.get("direction", "forward")))
        lines.append("  },")
    lines.append("};")
    lines.append(ANIMS_END)
    return "\n".join(lines) + "\n"


def update_anims_block(text, anims):
    block = anims_block_text(anims)
    if ANIMS_BEGIN in text:
        pat = re.compile(re.escape(ANIMS_BEGIN) + r".*?" + re.escape(ANIMS_END) + r"\n?", re.S)
        return pat.sub(block, text, count=1)
    return text.rstrip("\n") + "\n" + block


def sync_game(game_path, sprites_text):
    """game/index.html 内の window.MIYUKE_SPRITES 代入と MIYUKE_ANIMS ブロックを
    sprites.js と同一にする"""
    game = open(game_path, encoding="utf-8").read()
    changed = False

    def grab(txt):
        i = txt.index("window.MIYUKE_SPRITES")
        j = txt.index("\n};", i) + 3
        return txt[i:j], i, j
    new_assign, _, _ = grab(sprites_text)
    _, gi, gj = grab(game)
    if game[gi:gj] != new_assign:
        game = game[:gi] + new_assign + game[gj:]
        changed = True
    # ANIMS ブロック（マーカー区間ごと差し替え。ゲーム側に無ければ代入の直後へ挿入）
    if ANIMS_BEGIN not in sprites_text:
        if changed:
            open(game_path, "w", encoding="utf-8").write(game)
        return changed
    sb = sprites_text.index(ANIMS_BEGIN)
    se = sprites_text.index(ANIMS_END) + len(ANIMS_END)
    sblock = sprites_text[sb:se]
    if ANIMS_BEGIN in game:
        gb = game.index(ANIMS_BEGIN)
        ge = game.index(ANIMS_END) + len(ANIMS_END)
        if game[gb:ge] != sblock:
            game = game[:gb] + sblock + game[ge:]
            changed = True
    else:
        _, gi, gj = grab(game)
        game = game[:gj] + "\n" + sblock + game[gj:]
        changed = True
    if changed:
        open(game_path, "w", encoding="utf-8").write(game)
    return changed


# ------------------------------------------------------------------ main ---
def main():
    ap = argparse.ArgumentParser(description="sakuriさんのドット絵をゲーム用スプライトに変換")
    ap.add_argument("kind", choices=["sheet", "aseprite", "anims"])
    ap.add_argument("input", help="入力ファイル")
    ap.add_argument("--name", default=None, help="基準スプライト名 (例: miyuke_idle。anims では不要)")
    ap.add_argument("--cell", default="48x40", help="シートのセルサイズ WxH (sheet のみ)")
    ap.add_argument("--frame-ms", type=int, default=100,
                    help="シート入力時の 1 フレーム時間 ms (既定 100)")
    ap.add_argument("--override-ms", type=int, default=None,
                    help="全フレームの duration をこの値 ms で一律上書きする "
                         "(aseprite/sheet 共通。作家の口頭修正用)")
    ap.add_argument("--loop", default=None,
                    help="ループ区間 FROM:TO[xN|xinf] (1始まり)。タグがあればそちら優先")
    ap.add_argument("--static", action="store_true",
                    help="アニメにせず base 名そのままで 1 枚だけ取り込む (小物用)")
    ap.add_argument("--sprites", default=DEFAULT_SPRITES)
    ap.add_argument("--game", default=DEFAULT_GAME)
    ap.add_argument("--no-game", action="store_true", help="game/index.html へ同期しない")
    ap.add_argument("--no-validate", action="store_true", help="終了時の自動検証をしない")
    ap.add_argument("--fail-on-new-color", action="store_true",
                    help="未知の色があったらパレット拡張せずエラーにする")
    args = ap.parse_args()

    sprites_text = open(args.sprites, encoding="utf-8").read()

    # ---- anims モード: 既存スプライトへの ANIMS 定義だけを JSON から追加/更新する
    # （新規アートは作らない。既存フレームの機械的なアニメ化専用）
    if args.kind == "anims":
        extra = json.load(open(args.input, encoding="utf-8"))
        anims = load_existing_anims(sprites_text)
        for base, a in extra.items():
            cnt = a.get("loopCount", "Infinity")
            anims[base] = {
                "frames": a["frames"],
                "durations": [int(d) for d in a["durations"]],
                "loopFrom": int(a["loopFrom"]), "loopTo": int(a["loopTo"]),
                "loopCount": float("inf") if cnt in ("Infinity", "inf") else int(cnt),
                "direction": a.get("direction", "forward"),
            }
            for fn in a["frames"]:
                if ("    %s: [" % fn) not in sprites_text:
                    print("WARNING: frame sprite '%s' not found in sprites.js" % fn)
        new_text = update_anims_block(sprites_text, anims)
        open(args.sprites, "w", encoding="utf-8").write(new_text)
        synced = sync_game(args.game, new_text) if not args.no_game else False
        print("== import audit: anims (%s) ==" % args.input)
        print("anims now: %s" % ", ".join(sorted(anims)))
        print("sprites.js updated; game/index.html synced: %s" % synced)
        if not args.no_validate:
            print("== validate-sprites.cjs ==")
            r = subprocess.run(["node", DEFAULT_VALIDATE], capture_output=True, text=True)
            for line in (r.stdout + r.stderr).strip().splitlines()[-6:]:
                print("  " + line)
            if r.returncode != 0:
                print("ERROR: validation failed")
                return 1
        return 0

    if not args.name:
        print("ERROR: --name が必要です (sheet / aseprite)")
        return 1
    palette = load_palette(sprites_text)
    orig_size = len(palette)
    hex_to_char = {v: k for k, v in palette.items()}
    tags = []

    if args.kind == "sheet":
        cw, chh = (int(v) for v in args.cell.lower().split("x"))
        frames = read_sheet(args.input, cw, chh)
        durations = [args.frame_ms] * len(frames)
    else:
        frames, durations, tags = parse_aseprite(args.input)

    if args.override_ms:
        print("durations OVERRIDDEN: %s -> all %d frames at %dms (artist correction)"
              % (durations, len(frames), args.override_ms))
        durations = [args.override_ms] * len(frames)

    if args.static and len(frames) != 1:
        print("ERROR: --static は 1 フレームだけの入力用です (frames=%d)" % len(frames))
        return 1

    all_rows, audit = frames_to_rows(frames, palette, hex_to_char)
    if audit["added"] and args.fail_on_new_color:
        print("ERROR: unknown colors would extend the palette: %s" % audit["added"])
        return 1

    new_text = update_sprites_js(sprites_text, args.name, all_rows, palette, orig_size,
                                 static=args.static)

    # ---- ANIMS 定義（複数フレームのときだけ生成ブロックへ反映）
    loop_info = None
    if not args.static and len(frames) > 1:
        anims = load_existing_anims(new_text)
        loop_from, loop_to, loop_count, loop_src, loop_dir = resolve_loop(len(frames), tags, args.loop)
        if not (0 <= loop_from <= loop_to < len(frames)):
            print("ERROR: loop range %d..%d is outside 0..%d"
                  % (loop_from, loop_to, len(frames) - 1))
            return 1
        anims[args.name] = {
            "frames": ["%s_%d" % (args.name, i) for i in range(len(frames))],
            "durations": [int(d) for d in durations],
            "loopFrom": loop_from, "loopTo": loop_to, "loopCount": loop_count,
            "direction": loop_dir,
        }
        new_text = update_anims_block(new_text, anims)
        total = None
        if loop_count != float("inf"):
            intro = sum(durations[:loop_from])
            loopms = sum(durations[loop_from:loop_to + 1])
            outro = sum(durations[loop_to + 1:])
            total = intro + loopms * int(loop_count) + outro
        loop_info = (loop_from, loop_to, loop_count, loop_src, total, loop_dir)

    open(args.sprites, "w", encoding="utf-8").write(new_text)

    synced = False
    if not args.no_game:
        synced = sync_game(args.game, new_text)

    # ---- audit 出力
    print("== import audit: %s (%s) ==" % (args.name, args.kind))
    print("frames: %d" % len(all_rows))
    if durations:
        print("durations(ms): %s" % durations)
    if tags:
        print("aseprite tags: %s" % tags)
    if loop_info:
        lf, lt, lc, src, total, ldir = loop_info
        print("ANIMS: loop frames %d..%d (0-based) x%s via %s; direction=%s; total=%s"
              % (lf, lt, lc, src, ldir, (total if total is not None else "Infinity")))
    for i, rows in enumerate(all_rows):
        w = len(rows[0]) if rows else 0
        ragged = any(len(r) != w for r in rows)
        label = args.name if args.static else "%s_%d" % (args.name, i)
        print("  %s: %dx%d%s" % (label, w, len(rows), " RAGGED!" if ragged else ""))
    print("opaque colors used: %d" % len(audit["used_hex"]))
    if audit["added"]:
        print("PALETTE EXTENDED: %s" % audit["added"])
    else:
        print("palette: exact match, no extension")
    if audit["semi_alpha"]:
        print("WARNING: %d semi-transparent pixels (first: %s)"
              % (len(audit["semi_alpha"]), audit["semi_alpha"][0]))
    print("sprites.js updated; game/index.html synced: %s" % synced)

    # ---- 検証を自動実行
    if not args.no_validate:
        print("== validate-sprites.cjs ==")
        r = subprocess.run(["node", DEFAULT_VALIDATE], capture_output=True, text=True)
        tail = (r.stdout + r.stderr).strip().splitlines()
        for line in tail[-6:]:
            print("  " + line)
        if r.returncode != 0:
            print("ERROR: validation failed")
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
